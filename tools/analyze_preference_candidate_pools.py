#!/usr/bin/env python3
"""Re-score fixed pooled candidates to separate preference choice from discovery.

Exploratory diagnostic: pools combine four already-executed 64-proposal traces;
not a new 64-proposal RACE-RL run or a comparison against a baseline algorithm.
"""
import argparse,collections,hashlib,json,math,statistics
from pathlib import Path

PREFS=('balanced','power','performance','area')
WEIGHTS={'balanced':(1/3,1/3,1/3),'power':(.6,.2,.2),'performance':(.2,.6,.2),'area':(.2,.2,.6)}
KEYS=('average_power_w','latency_s','area_mm2');LIMITS=('max_power_w','max_latency_s','max_area_mm2');TARGET={'power':0,'performance':1,'area':2}
def read(p):return json.loads(p.read_text())
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--root',type=Path,required=True);p.add_argument('--out',type=Path,required=True);args=p.parse_args()
 if args.out.exists():raise FileExistsError(args.out)
 names=('reference_v2','exploratory_latency_x2','exploratory_latency_x2_area_x05');trials=[];provenance={}
 for cond in names:
  folder=args.root/cond;suite=read(folder/'suite_protocol.json');audit=read(folder/'analysis.json')
  if suite['methods']!=['reinforce'] or set(suite['preferences'])!=set(PREFS) or suite['budget']!=64 or audit['trial_count']!=60:raise ValueError(f'incomplete or incompatible {cond}')
  provenance[f'{cond}/suite_protocol.json']=sha(folder/'suite_protocol.json');provenance[f'{cond}/analysis.json']=sha(folder/'analysis.json')
  for model in suite['models']:
   lim=[suite['limits'][model][k] for k in LIMITS]
   for seed in suite['seeds']:
    pool={};traces={};actual={}
    for pref in PREFS:
     path=folder/'runs'/model/pref/str(seed)/'reinforce.json';key=str(path.relative_to(folder));d=read(path)
     if sha(path)!=audit['method_results_sha256'][key]:raise ValueError('checksum mismatch '+str(path))
     provenance[f'{cond}/{key}']=sha(path);actual[pref]=d['result']['best_assessment'];ts=[t for ep in d['episodes'] for t in ep['trace']];
     if len(ts)!=suite['budget']:raise ValueError('bad trace length')
     traces[pref]=ts
     for t in ts:
      if not t.get('physical_feasible'):continue
      ppa=t.get('ppa') or {};v=tuple(ppa.get(k) for k in KEYS);h=t.get('design_hash')
      if not h or not all(isinstance(x,(float,int)) and math.isfinite(x) and x>0 for x in v):continue
      if h in pool and pool[h]!=v:raise ValueError('design hash has conflicting metrics')
      pool[h]=v
    feasible={h:v for h,v in pool.items() if all(x<=upper for x,upper in zip(v,lim))}
    selected={}
    for pref in PREFS:
     if feasible:
      h,v=min(feasible.items(),key=lambda item:(math.fsum(w*x/l for w,x,l in zip(WEIGHTS[pref],item[1],lim)),item[0]));selected[pref]={'design_hash':h,'metrics':dict(zip(KEYS,v)),'cost':math.fsum(w*x/l for w,x,l in zip(WEIGHTS[pref],v,lim))}
     else:selected[pref]=None
    target_minima={}
    for pref,ix in TARGET.items():
     if feasible:
      h,v=min(feasible.items(),key=lambda item:(item[1][ix],item[0]))
      target_minima[pref]={'design_hash':h,'metrics':dict(zip(KEYS,v))}
     else:target_minima[pref]=None
    trace_same={pref:sum(a['design_hash']==b['design_hash'] for a,b in zip(traces['balanced'],traces[pref])) for pref in PREFS[1:]}
    first_same={pref:traces['balanced'][0]['choices']==traces[pref][0]['choices'] for pref in PREFS[1:]}
    trials.append({'scenario':cond,'model':model,'seed':seed,'unique_physical_candidates':len(pool),'feasible_pool_size':len(feasible),'pool_selected':selected,'target_minima':target_minima,'original_best':actual,'matched_hashes_per_64':trace_same,'first_choices_equal':first_same})
 output={'status':'EXPLORATORY_POOLED_OFFLINE_NOT_NEW_POLICY_RUN','caveats':['pool combines up to 256 proposals generated by four preference-specific 64-proposal searches; not equal budget','re-scoring same fixed pool tests outcome selection, not RL learning or policy generalization','candidate pool itself was discovered using those preference-conditioned searches','ties broken by design hash; compare actual metrics before interpreting'], 'source_files_sha256':provenance,'trials':trials,'summaries':[]}
 for cond in names:
  for model in ('resnet18','mobilenet_v2','vgg16'):
   group=[t for t in trials if t['scenario']==cond and t['model']==model];entry={'scenario':cond,'model':model,'pool_size_median':statistics.median(t['feasible_pool_size'] for t in group),'preferences':{}}
   for pref in PREFS[1:]:
    ix=TARGET[pref];k=KEYS[ix];g=[t for t in group if t['pool_selected']['balanced'] and t['pool_selected'][pref]]
    strict=sum(t['pool_selected'][pref]['metrics'][k]<t['pool_selected']['balanced']['metrics'][k]-1e-12 for t in g)
    # Cost under the SAME preference, rather than comparing across weights.
    costwins=0
    for t in g:
     b=t['pool_selected']['balanced']['metrics'];c=t['pool_selected'][pref]['metrics'];lim=[read(args.root/cond/'suite_protocol.json')['limits'][model][x] for x in LIMITS]
     cb=math.fsum(w*b[x]/l for w,x,l in zip(WEIGHTS[pref],KEYS,lim));cp=math.fsum(w*c[x]/l for w,x,l in zip(WEIGHTS[pref],KEYS,lim));costwins+=cp<cb-1e-12
    entry['preferences'][pref]={'seed_count':len(g),'target_lower_than_balanced':strict,'pool_contains_lower_target':sum(t['target_minima'][pref]['metrics'][k]<t['pool_selected']['balanced']['metrics'][k]-1e-12 for t in g),'selected_different_design':sum(t['pool_selected'][pref]['design_hash']!=t['pool_selected']['balanced']['design_hash'] for t in g),'preferred_cost_strictly_lower':costwins,'median_same_step_hashes':statistics.median(t['matched_hashes_per_64'][pref] for t in group),'identical_full_trajectories':sum(t['matched_hashes_per_64'][pref]==64 for t in group),'identical_first_choices':sum(t['first_choices_equal'][pref] for t in group)}
   output['summaries'].append(entry)
 args.out.parent.mkdir(parents=True,exist_ok=True);args.out.write_text(json.dumps(output,ensure_ascii=False,indent=2)+'\n')
 for x in output['summaries']:
  print(x['scenario'],x['model'],'可行候選中位數',x['pool_size_median'],[(p,v['target_lower_than_balanced'],v['selected_different_design'],v['preferred_cost_strictly_lower'],v['identical_full_trajectories']) for p,v in x['preferences'].items()])
 print('已儲存',args.out)
if __name__=='__main__':main()
